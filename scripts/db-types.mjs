#!/usr/bin/env node
// Generates src/lib/db/schema.ts from the migration chain itself: the chain is
// replayed into an in-process PostgreSQL (PGlite) and the resulting catalog is
// read back. The types therefore describe the schema the migrations actually
// build, not a hand-kept copy of it, and `--check` (run in CI) fails when a
// migration lands without regenerating them.
//
//   node scripts/db-types.mjs           write src/lib/db/schema.ts
//   node scripts/db-types.mjs --check   exit 1 if the committed file is stale

import fs from "node:fs";
import { fileURLToPath } from "node:url";

import { PGlite } from "@electric-sql/pglite";
import { pgcrypto } from "@electric-sql/pglite/contrib/pgcrypto";

import { migrate, readMigrations } from "../db/migrate.mjs";

const OUTPUT = fileURLToPath(new URL("../src/lib/db/schema.ts", import.meta.url));

// How each PostgreSQL type arrives in TypeScript. This must agree with the
// result parsers in src/lib/db/parsers.ts, which return timestamps and dates as
// ISO strings and bigint as a number, the way the database API used to.
const SCALARS = {
  text: "string",
  "character varying": "string",
  uuid: "string",
  integer: "number",
  smallint: "number",
  bigint: "number",
  boolean: "boolean",
  "timestamp with time zone": "string",
  date: "string",
  jsonb: "Json",
  json: "Json",
};

function tsType(pgType) {
  if (pgType.endsWith("[]")) return `${tsType(pgType.slice(0, -2))}[]`;
  const mapped = SCALARS[pgType];
  if (!mapped) throw new Error(`No TypeScript mapping for PostgreSQL type "${pgType}"; add one to SCALARS.`);
  return mapped;
}

const pascal = (name) => name.replace(/(^|_)([a-z0-9])/g, (_, __, letter) => letter.toUpperCase());

export async function generate() {
  const database = await PGlite.create({ extensions: { pgcrypto } });
  try {
    await migrate(database);
    const columns = (await database.query(`
      select c.table_name, c.column_name, format_type(a.atttypid, a.atttypmod) as type,
             c.is_nullable = 'YES' as nullable,
             c.column_default is not null or c.is_identity = 'YES' as generated
      from information_schema.columns c
      join pg_attribute a
        on a.attrelid = format('public.%I', c.table_name)::regclass and a.attname = c.column_name
      join information_schema.tables t
        on t.table_schema = c.table_schema and t.table_name = c.table_name and t.table_type = 'BASE TABLE'
      where c.table_schema = 'public' and c.table_name <> 'schema_migrations'
      order by c.table_name, c.ordinal_position`)).rows;
    const functionArgs = (await database.query(`
      select p.proname as function, a.position, a.name, a.mode, format_type(a.type, null) as type,
             p.pronargs as input_count, p.pronargdefaults as default_count,
             p.proretset as returns_set, format_type(p.prorettype, null) as return_type
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
      cross join lateral unnest(
        coalesce(p.proallargtypes, p.proargtypes::oid[]),
        coalesce(p.proargmodes, array_fill('i'::"char", array[p.pronargs])),
        p.proargnames
      ) with ordinality as a(type, mode, name, position)
      where n.nspname = 'public' and p.prorettype <> 'trigger'::regtype
      order by p.proname, a.position`)).rows;
    return render(columns, functionArgs);
  } finally {
    await database.close();
  }
}

function render(columns, functionArgs) {
  const tables = new Map();
  for (const column of columns) {
    if (!tables.has(column.table_name)) tables.set(column.table_name, []);
    tables.get(column.table_name).push(column);
  }

  const functions = new Map();
  for (const row of functionArgs) {
    if (!functions.has(row.function)) functions.set(row.function, { ...row, inputs: [], outputs: [] });
    const entry = functions.get(row.function);
    if (row.mode === "i") entry.inputs.push(row);
    else if (row.mode === "t" || row.mode === "o") entry.outputs.push(row);
  }

  const lines = [
    "// Generated by scripts/db-types.mjs from db/migrations. Do not edit by hand:",
    "// add a migration, then run `pnpm db:types`. CI fails if this file is stale.",
    "",
    'import type { Generated } from "kysely";',
    "",
    "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];",
    "",
  ];

  for (const [table, tableColumns] of tables) {
    lines.push(`export interface ${pascal(table)}Table {`);
    for (const column of tableColumns) {
      let type = tsType(column.type);
      if (column.nullable) type = `${type} | null`;
      if (column.generated) type = `Generated<${type}>`;
      lines.push(`  ${column.column_name}: ${type};`);
    }
    lines.push("}", "");
  }

  const latest = readMigrations().at(-1)?.name;
  lines.push(
    "/**",
    " * The newest migration this code was built against. Readiness reports the",
    " * database unready until it is recorded in public.schema_migrations, so a",
    " * deploy that runs ahead of its migration says so instead of failing later.",
    " */",
    `export const SCHEMA_VERSION = "${latest}";`,
    "",
  );

  lines.push("export interface Database {");
  for (const table of tables.keys()) lines.push(`  ${table}: ${pascal(table)}Table;`);
  lines.push("}", "");

  const scoped = [...tables].filter(([, tableColumns]) => tableColumns.some((column) => column.column_name === "user_id"));
  lines.push(
    "/** Every table with a user_id column. The tenant guard refuses unscoped queries against these. */",
    "export const USER_SCOPED_TABLES = [",
    ...scoped.map(([table]) => `  "${table}",`),
    "] as const satisfies readonly (keyof Database)[];",
    "",
  );

  lines.push("/** SQL functions in `public`, with the PostgreSQL type of each argument. */");
  lines.push("export const FUNCTION_ARGUMENTS = {");
  for (const [name, fn] of functions) {
    lines.push(`  ${name}: {`);
    for (const input of fn.inputs) lines.push(`    ${input.name}: "${input.type}",`);
    lines.push("  },");
  }
  lines.push("} as const;", "");

  lines.push(
    "/** Functions declared `returns table (…)`; the rest return a single value. */",
    "export const TABLE_FUNCTIONS: ReadonlySet<string> = new Set([",
    ...[...functions].filter(([, fn]) => fn.outputs.length).map(([name]) => `  "${name}",`),
    "]);",
    "",
  );

  lines.push("export interface Functions {");
  for (const [name, fn] of functions) {
    const optionalFrom = fn.input_count - fn.default_count;
    lines.push(`  ${name}: {`);
    lines.push("    args: {");
    fn.inputs.forEach((input, index) => {
      lines.push(`      ${input.name}${index >= optionalFrom ? "?" : ""}: ${tsType(input.type)} | null;`);
    });
    lines.push("    };");
    if (fn.outputs.length) {
      const fields = fn.outputs.map((output) => `${output.name}: ${tsType(output.type)} | null`).join("; ");
      lines.push(`    returns: { ${fields} }[];`);
    } else {
      lines.push(`    returns: ${tsType(fn.return_type)}${fn.returns_set ? "[]" : ""} | null;`);
    }
    lines.push("  };");
  }
  lines.push("}", "");

  return lines.join("\n");
}

async function main() {
  const source = await generate();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, "utf8") : "";
    if (current !== source) {
      console.error("src/lib/db/schema.ts is stale. Run `pnpm db:types` and commit the result.");
      process.exit(1);
    }
    console.log("src/lib/db/schema.ts matches the migrations.");
    return;
  }
  fs.mkdirSync(new URL("../src/lib/db/", import.meta.url), { recursive: true });
  fs.writeFileSync(OUTPUT, source);
  console.log("Wrote src/lib/db/schema.ts.");
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
